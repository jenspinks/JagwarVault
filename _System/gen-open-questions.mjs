#!/usr/bin/env node
// _System/gen-open-questions.mjs — consolidate every open question into one checklist (CLAUDE.md §8).
// Walks Brain/ + Essays/, pulls (a) non-resolved items under each page's `## Open Questions`
// heading and (b) any `- [ ]` checkbox anywhere, and writes _System/open-questions.md grouped by page.
// Deterministic: pass --date=YYYY-MM-DD to stamp; otherwise the date token is left literal so re-runs
// are byte-identical (no Date.now() — autosync-friendly). Run: node _System/gen-open-questions.mjs [--date=2026-06-17]
import { readdirSync, writeFileSync, statSync } from "node:fs";
import { join, extname } from "node:path";
import { readFrontmatter } from "./lib-frontmatter.mjs";

const ROOT = new URL("..", import.meta.url).pathname;

// --date=YYYY-MM-DD (or `--date YYYY-MM-DD`); else leave a literal token (determinism over a churning date).
function argDate() {
  const eq = process.argv.find((a) => a.startsWith("--date="));
  if (eq) return eq.slice("--date=".length);
  const i = process.argv.indexOf("--date");
  if (i !== -1 && process.argv[i + 1]) return process.argv[i + 1];
  return "{{date}}";
}
const DATE = argDate();

// Mirror validate.mjs / backlink.mjs walk.
function walk(dir) {
  const abs = join(ROOT, dir);
  let out = [];
  let entries;
  try { entries = readdirSync(abs); } catch { return out; }
  for (const e of entries) {
    if (e.startsWith(".")) continue;
    const p = join(abs, e);
    if (statSync(p).isDirectory()) out = out.concat(walk(join(dir, e)));
    else if (extname(e) === ".md") out.push(join(dir, e));
  }
  return out;
}
const pages = [...walk("Brain"), ...walk("Essays")].sort(); // sorted = deterministic output

// Pull open-question items from one page body → normalized `- [ ] …` lines (deduped, doc order).
// Sources: (a) non-resolved list items under a `## Open Questions` heading; (b) `- [ ]` anywhere.
function extract(rawBody) {
  const body = rawBody.replace(/```[\s\S]*?```/g, ""); // drop fenced code so `- [ ]` examples don't count
  const items = [];
  const seen = new Set();
  let inOQ = false;
  for (const raw of body.split(/\r?\n/)) {
    if (/^#{1,6}\s/.test(raw)) { inOQ = /^#{2,6}\s+open questions\b/i.test(raw); continue; }
    const li = raw.match(/^\s*-\s+(.*)$/);
    if (!li) continue;
    const cb = li[1].match(/^\[(.)\]\s*(.*)$/); // single-char checkbox token: [ ] [x] [?] [~] …
    const mark = cb ? cb[1] : null;
    const text = (cb ? cb[2] : li[1]).trim();
    const resolved = mark === "x" || mark === "X"; // [x] = done → not open
    const openBox = mark === " ";                  // [ ] = open checkbox
    if (!(openBox || (inOQ && !resolved))) continue; // keep: any [ ], or any non-resolved item under OQ
    if (!text) continue;
    const norm = `- [ ] ${text}`;
    if (!seen.has(norm)) { seen.add(norm); items.push(norm); }
  }
  return items;
}

const sections = [];
let total = 0;
for (const rel of pages) {
  const { body } = readFrontmatter(join(ROOT, rel));
  const items = extract(body);
  if (!items.length) continue; // skip pages with no open questions
  total += items.length;
  // clickable relative-path heading; angle-bracket URL tolerates spaces + parens in vault paths
  sections.push(`## [${rel}](<../${rel}>)\n${items.join("\n")}`);
}

const out =
`---
type: reference
citable: false
status: stable
---
# Open Questions — consolidated

> [!warning] Snapshot — may lag
> Generated by \`node _System/gen-open-questions.mjs\`; **regenerate after editing pages.** Each page's own \`## Open Questions\` section is the source of truth. Pass \`--date=YYYY-MM-DD\` to stamp. Generated: ${DATE}.

**${total} open questions across ${sections.length} pages.**

${sections.join("\n\n")}
`;

writeFileSync(join(ROOT, "_System/open-questions.md"), out);
console.log(`gen-open-questions: ${total} open questions across ${sections.length} pages → _System/open-questions.md`);
